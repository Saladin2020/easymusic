/**
 * Easy Music web player (no dependencies; works next to PixiJS v8 or any web game).
 *
 *   import { loadMusic } from "./easymusic-web.js";
 *   const music = await loadMusic("easymusic.json");
 *   await music.play("village_day");          // decodes on first play, loops from the loop point
 *   await music.play("battle_chip", { fade: 0.5 });
 *   music.stop({ fade: 1 });
 *
 * Browsers start audio only after a user gesture: call play() from a click / key / pointertap handler
 * (e.g. Pixi: sprite.on("pointertap", () => music.play("shop_theme"))).
 * Picks the .ogg when the browser can decode Vorbis, else the .wav. Generated by Easy Music (MIT).
 */

export async function loadMusic(manifestUrl, opts = {}) {
  const base = new URL(manifestUrl, document.baseURI);
  const manifest = await (await fetch(base)).json();
  const songs = new Map(manifest.songs.map((s) => [s.id, s]));
  const ctx = opts.context ?? new AudioContext();
  const master = ctx.createGain();
  master.gain.value = opts.volume ?? 1;
  master.connect(ctx.destination);
  const canOgg = typeof Audio !== "undefined" && new Audio().canPlayType('audio/ogg; codecs="vorbis"') !== "";
  const buffers = new Map();
  let cur = null;

  async function buffer(id) {
    const s = songs.get(id);
    if (!s) throw new Error(`easymusic: unknown song "${id}" (have ${[...songs.keys()].join(", ")})`);
    if (!buffers.has(id)) {
      const file = (canOgg && s.ogg) || s.wav || s.ogg;
      buffers.set(id, fetch(new URL(file, base)).then((r) => r.arrayBuffer()).then((b) => ctx.decodeAudioData(b)));
    }
    return buffers.get(id);
  }

  function fadeOut(entry, t) {
    const now = ctx.currentTime;
    entry.gain.gain.cancelScheduledValues(now);
    entry.gain.gain.setValueAtTime(entry.gain.gain.value, now);
    entry.gain.gain.linearRampToValueAtTime(0, now + Math.max(0.01, t));
    entry.src.stop(now + Math.max(0.01, t) + 0.05);
  }

  return {
    ids: [...songs.keys()],
    info: (id) => songs.get(id),
    context: ctx,
    preload: (ids = [...songs.keys()]) => Promise.all(ids.map(buffer)),
    async play(id, { fade = 1 } = {}) {
      if (ctx.state === "suspended") await ctx.resume();
      if (cur && cur.id === id) return;
      const s = songs.get(id);
      const buf = await buffer(id);
      const src = ctx.createBufferSource();
      src.buffer = buf;
      src.loop = true;
      src.loopStart = s.loopStart;
      src.loopEnd = buf.duration;
      const gain = ctx.createGain();
      src.connect(gain).connect(master);
      const now = ctx.currentTime;
      gain.gain.setValueAtTime(fade > 0 ? 0 : 1, now);
      if (fade > 0) gain.gain.linearRampToValueAtTime(1, now + fade);
      src.start(now);
      if (cur) fadeOut(cur, fade);
      cur = { id, src, gain, started: now, loopStart: s.loopStart, duration: buf.duration };
    },
    stop({ fade = 1 } = {}) {
      if (cur) fadeOut(cur, fade);
      cur = null;
    },
    setVolume(v) {
      master.gain.value = v;
    },
    /** { id, seconds (position in the file), duration, loops } or null. */
    position() {
      if (!cur) return null;
      const t = ctx.currentTime - cur.started;
      const loopLen = cur.duration - cur.loopStart;
      if (t < cur.duration) return { id: cur.id, seconds: t, duration: cur.duration, loops: 0 };
      const k = Math.floor((t - cur.duration) / loopLen) + 1;
      return { id: cur.id, seconds: cur.loopStart + ((t - cur.duration) % loopLen), duration: cur.duration, loops: k };
    },
  };
}
